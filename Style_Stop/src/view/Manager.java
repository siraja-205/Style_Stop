    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String q = jTextField7.getText().trim();
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) jTable1.getModel();
        javax.swing.table.TableRowSorter<javax.swing.table.DefaultTableModel> sorter;
        if (jTable1.getRowSorter() instanceof javax.swing.table.TableRowSorter) {
            sorter = (javax.swing.table.TableRowSorter<javax.swing.table.DefaultTableModel>) jTable1.getRowSorter();
        } else {
            sorter = new javax.swing.table.TableRowSorter<>(model);
            jTable1.setRowSorter(sorter);
        }
        if (q.isEmpty()) {
            sorter.setRowFilter(null);
            return;
        }
        javax.swing.RowFilter<javax.swing.table.DefaultTableModel, Object> rf =
        javax.swing.RowFilter.regexFilter("(?i)" + java.util.regex.Pattern.quote(q));
        sorter.setRowFilter(rf);
        if (jTable1.getRowCount() == 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "No matching products", "Search", javax.swing.JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

