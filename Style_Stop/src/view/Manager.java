    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        int row = jTable1.getSelectedRow();
        if (row == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Select a row to delete", "Delete", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        int modelRow = jTable1.convertRowIndexToModel(row);
        productController.delete(modelRow);
        productController.refresh((javax.swing.table.DefaultTableModel) jTable1.getModel());
        javax.swing.JOptionPane.showMessageDialog(this, "Deleted selected product", "Delete", javax.swing.JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_jButton4ActionPerformed

